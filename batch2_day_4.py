"""1. find how many vowels, consonants, spaces and special characters"""

x="python is a programmming language."
vowels="aeiouAeiou"
vowel_count=consonant_count=space_count=special_char_count=0
for char in x:
  if char.isalpha():
    if char in vowels:
      vowel_count+=1
    else:
      consonant_count+=1
  elif char.isspace():
    space_count+=1
  else:
    special_char_count+=1
print(f"Vowels:{vowel_count}")
print(f"Consonants:{consonant_count}")
print(f"Spaces:{space_count}")
print(f"Special Characters:{special_char_count}")

