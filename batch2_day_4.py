"""4. write a code to find it is a anagram or not

"""

str1 = input("Enter first string: ")
str2 = input("Enter second string: ")
if len(str1) != len(str2):
    print("Not anagram")
else:
    count = {}
    for ch in str1:
        count[ch] = count.get(ch, 0) + 1
    for ch in str2:
        count[ch] = count.get(ch, 0) - 1
    if all(value == 0 for value in count.values()):
        print("Anagram")
    else:
        print("Not anagram")

